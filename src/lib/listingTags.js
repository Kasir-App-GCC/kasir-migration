export function getListingTags(category, subcategory, condition) {
  const cat = LISTING_TAGS[category];
  if (!cat) return [];
  const subs = Array.isArray(subcategory) ? subcategory : (subcategory ? [subcategory] : []);
  const targets = subs.length ? subs : [];
  let tags = [];
  for (const s of targets) {
    const slug = s.toLowerCase().replace(/[^a-z0-9]+/g, '_').replace(/^_|_$/g, '');
    const def = cat[slug] || cat[s];
    if (def) tags = tags.concat(def);
  }
  const seen = new Set();
  tags = tags.filter((t) => { if (seen.has(t.en)) return false; seen.add(t.en); return true; });
  return tags.map(({ en, ar }) => ({ en, ar }));
}

export function localizeListingTag(value, lang) {
  for (const cat of Object.keys(LISTING_TAGS)) {
    const subs = LISTING_TAGS[cat];
    for (const subKey of Object.keys(subs)) {
      const found = subs[subKey].find((t) => t.en === value);
      if (found) return lang === "ar" ? found.ar : found.en;
    }
  }
  return value;
}
